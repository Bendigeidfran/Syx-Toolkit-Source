package syx.core;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import syx.core.TagLocator.Located;

/**
 * The portrait tags of a race's sprite file, cut out as one piece of text and spliced back. The text of each value
 * is the file's own, so formatting and comments inside it survive, and everything else in the file stays as it was.
 */
public final class PortraitSection {

	/** The section can't be saved into the file. The message says why. */
	static final class Mismatch extends Exception {
		private static final long serialVersionUID = 1L;

		Mismatch(String message) {
			super(message);
		}
	}

	/** Why a section can't be saved. The line is in the section's text, or null if there's no one line to name. */
	record Issue(String message, Integer line) {
	}

	/** One absent tag with a default in the game code. */
	public record Absent(String key, String value) {
	}

	/** A block in the section, and the tags with a default it doesn't set. Offsets are of its braces. */
	public record AbsentBlock(String path, int start, int end, List<Absent> absent) {
	}

	private static final String FACE = "FACE";
	/** The portrait's tags: those RColors, RCrown and RPortrait read. */
	static final SpriteFileSection.Spec SPEC = new SpriteFileSection.Spec(List.of("COLOR_BLOOD", "COLORS", "CROWN", "RAIDER", "MERC"), List.of(FACE), "portrait tag");

	private record Edit(int start, int end, String text) {
	}

	private PortraitSection() {
	}

	private static SpriteFileSection.Layout layout(String text) {
		return SpriteFileSection.layout(text);
	}

	private static String raw(String text, Located place) {
		return SpriteFileSection.raw(text, place);
	}

	/** The section's text for a file, with \n line ends. A layout that can't be located throws a RuntimeException. */
	static String extract(String file) {
		return SpriteFileSection.extract(SPEC, file);
	}

	/** Whether the locator found the same tags as the game's parser, so it's safe to splice into this text. */
	static boolean agrees(String text, GameParser.Node root) throws GameParser.ReadException {
		return SpriteFileSection.agrees(text, root);
	}

	/** Why this text can't go back into the file, or null. The game's parser has already accepted it. */
	static Issue problem(String section, String file) {
		return SpriteFileSection.problem(SPEC, section, file);
	}

	/** The file with the section's values in it. Values that didn't change keep their exact bytes. */
	static String apply(String section, String file) throws Mismatch {
		return SpriteFileSection.apply(SPEC, section, file);
	}

	/** The file's tree with the section's tags in place of its own. What a saved file must read back as. */
	static GameTree.Block merged(GameTree.Block file, GameTree.Block section) {
		return SpriteFileSection.merged(SPEC, file, section);
	}

	/** Every block's absent tags with a default in the game code. Text the toolkit can't locate gives an empty list. */
	static List<AbsentBlock> absent(String section) {
		List<AbsentBlock> blocks = new ArrayList<>();
		try {
			SpriteFileSection.Layout layout = layout(section);
			SpriteFileSection.colourBlocks(blocks, section, layout);
			for (int i = 0; i < layout.typeBlocks().size(); i++) {
				faceBlocks(blocks, section, "TYPES." + i + ".FACE.", layout.typeBlocks().get(i).entry(FACE));
			}
			if (layout.childBlock() != null) {
				faceBlocks(blocks, section, "CHILD.FACE.", layout.childBlock().entry(FACE));
			}
		} catch (RuntimeException e) {
			return List.of();
		}
		return blocks;
	}

	private static void faceBlocks(List<AbsentBlock> blocks, String section, String prefix, Located face) {
		if (face == null || section.charAt(face.start()) != '[') {
			return;
		}
		List<Located> items = TagLocator.items(section, face);
		for (int i = 0; i < items.size(); i++) {
			if (section.charAt(items.get(i).start()) == '{') {
				// RPortraitFrame.java:68-80.
				Map<String, String> defaults = new LinkedHashMap<>();
				defaults.put("FRAME_RANDOM", String.valueOf(i % 16));
				defaults.put("FRAME_OCCURRENCE", "1");
				defaults.put("OFF_X", "0");
				defaults.put("OFF_Y", "0");
				defaults.put("OFF_X_RANDOM", "0");
				defaults.put("OFF_Y_RANDOM", "0");
				defaults.put("OPACITY", "255");
				defaults.put("STAINS", "true");
				SpriteFileSection.addBlock(blocks, section, prefix + i, items.get(i), defaults);
			}
		}
	}

	/** A change to make to the section's text. The end is exclusive. */
	public record TextEdit(int start, int end, String text) {
	}

	/** One entry of a colour's VALUES as written, or null if it's generated by FROM and TO, or isn't there. */
	private static Located colourEntry(String section, String name, int entry) {
		Located colors = layout(section).top().get("COLORS");
		if (colors == null || section.charAt(colors.start()) != '{') {
			return null;
		}
		for (Located colour : TagLocator.entries(section, colors)) {
			if (colour.key().equals(name) && section.charAt(colour.start()) == '{') {
				for (Located tag : TagLocator.entries(section, colour)) {
					if (tag.key().equals("VALUES")) {
						return valuesEntry(section, tag, entry);
					}
				}
			}
		}
		return null;
	}

	/** The forms ColorImp.cols accepts (ColorImp.java:69-100). */
	private static Located valuesEntry(String section, Located values, int entry) {
		if (section.charAt(values.start()) == '[') {
			List<Located> items = TagLocator.items(section, values);
			return entry >= 0 && entry < items.size() ? items.get(entry) : null;
		}
		if (entry != 0) {
			return null;
		}
		if (section.charAt(values.start()) == '{' && TagLocator.entries(section, values).stream().noneMatch(tag -> tag.key().equals("R"))) {
			return null;
		}
		return values;
	}

	/** A colour's new value, in the form it's already written in. A plain value is R_G_B, and a block keeps its layout. */
	private static TextEdit rgbEdit(String section, Located value, int r, int g, int b) {
		if (section.charAt(value.start()) == '{') {
			List<Located> tags = TagLocator.entries(section, value);
			Map<String, Located> byKey = new LinkedHashMap<>();
			tags.forEach(tag -> byKey.put(tag.key(), tag));
			if (byKey.containsKey("R") && byKey.containsKey("G") && byKey.containsKey("B")) {
				return channels(section, byKey, r, g, b);
			}
			return byKey.containsKey("COLOR") ? rgbEdit(section, byKey.get("COLOR"), r, g, b) : null;
		}
		if (section.charAt(value.start()) == '[' || section.charAt(value.start()) == '"') {
			return null;
		}
		return new TextEdit(value.start(), value.end(), r + "_" + g + "_" + b);
	}

	private static TextEdit channels(String section, Map<String, Located> byKey, int r, int g, int b) {
		List<Edit> edits = new ArrayList<>(List.of(new Edit(byKey.get("R").start(), byKey.get("R").end(), String.valueOf(r)),
				new Edit(byKey.get("G").start(), byKey.get("G").end(), String.valueOf(g)), new Edit(byKey.get("B").start(), byKey.get("B").end(), String.valueOf(b))));
		edits.sort(Comparator.comparingInt(Edit::start));
		StringBuilder text = new StringBuilder(edits.get(0).text());
		for (int i = 1; i < edits.size(); i++) {
			text.append(section, edits.get(i - 1).end(), edits.get(i).start()).append(edits.get(i).text());
		}
		return new TextEdit(edits.get(0).start(), edits.get(2).end(), text.toString());
	}

	/** A change setting one colour entry, or null if text that doesn't locate or a generated colour rules it out. */
	static TextEdit colourEdit(String section, String name, int entry, int r, int g, int b) {
		try {
			Located value = colourEntry(section, name, entry);
			return value == null ? null : rgbEdit(section, value, r, g, b);
		} catch (RuntimeException e) {
			return null;
		}
	}

	static TextEdit bloodEdit(String section, int r, int g, int b) {
		try {
			Located value = layout(section).top().get("COLOR_BLOOD");
			return value == null ? null : rgbEdit(section, value, r, g, b);
		} catch (RuntimeException e) {
			return null;
		}
	}

	/** A change putting a colour entry back as it is in the other text, or null. A null name means the blood colour. */
	static TextEdit colourReset(String section, String saved, String name, int entry) {
		try {
			Located now = name == null ? layout(section).top().get("COLOR_BLOOD") : colourEntry(section, name, entry);
			Located then = name == null ? layout(saved).top().get("COLOR_BLOOD") : colourEntry(saved, name, entry);
			return now == null || then == null ? null : new TextEdit(now.start(), now.end(), raw(saved, then));
		} catch (RuntimeException e) {
			return null;
		}
	}

	static Integer colourOffset(String section, String name, int entry) {
		try {
			Located value = name == null ? layout(section).top().get("COLOR_BLOOD") : colourEntry(section, name, entry);
			return value == null ? null : value.start();
		} catch (RuntimeException e) {
			return null;
		}
	}

	/** One FILE: ROW entry. The type counts the adults in order, then the child, as a preview's types do. */
	private static Located frameEntry(String section, int type, int part, int item) {
		SpriteFileSection.Layout layout = layout(section);
		SpriteFileSection.Inner block = type < layout.typeBlocks().size() ? layout.typeBlocks().get(type) : layout.childBlock();
		if (block == null || block.entry(FACE) == null) {
			return null;
		}
		List<Located> parts = TagLocator.items(section, block.entry(FACE));
		if (part < 0 || part >= parts.size() || section.charAt(parts.get(part).start()) != '{') {
			return null;
		}
		for (Located tag : TagLocator.entries(section, parts.get(part))) {
			if (tag.key().equals("FRAMES") && section.charAt(tag.start()) == '[') {
				List<Located> frames = TagLocator.items(section, tag);
				return item >= 0 && item < frames.size() ? frames.get(item) : null;
			}
		}
		return null;
	}

	/** A change pointing one FILE: ROW entry at another row. Only the number is touched. */
	static TextEdit frameRowEdit(String section, int type, int part, int item, int row) {
		try {
			Located entry = frameEntry(section, type, part, item);
			if (entry == null) {
				return null;
			}
			int colon = section.lastIndexOf(':', entry.end() - 1);
			if (colon < entry.start()) {
				return null;
			}
			int start = colon + 1;
			while (start < entry.end() && Character.isWhitespace(section.charAt(start))) {
				start++;
			}
			int end = entry.end();
			while (end > start && Character.isWhitespace(section.charAt(end - 1))) {
				end--;
			}
			return new TextEdit(start, end, String.valueOf(row));
		} catch (RuntimeException e) {
			return null;
		}
	}

	static Integer frameOffset(String section, int type, int part, int item) {
		try {
			Located entry = frameEntry(section, type, part, item);
			return entry == null ? null : entry.start();
		} catch (RuntimeException e) {
			return null;
		}
	}

	/** The block holding this offset, or null. A nested block is listed after no other block it could be inside. */
	static AbsentBlock blockAt(List<AbsentBlock> blocks, int offset) {
		for (AbsentBlock block : blocks) {
			if (offset > block.start() && offset < block.end()) {
				return block;
			}
		}
		return null;
	}

	/** The text with a tag added at the end of the block at this offset, indented to match. */
	static String withTag(String section, AbsentBlock block, String key, String value) {
		int close = block.end() - 1;
		String indent = SpriteFileSection.closingIndent(section, close);
		return section.substring(0, close) + "\t" + key + ": " + value + ",\n" + indent + section.substring(close);
	}
}
